public class OutputVariable {
    public static void main(String[] args) {
        int value = 10;
        char x;
        x = 'A';
        System.out.println(value);
        System.out.println("The value of x=" + x);

        // Deklarasikan variabel result bertipe boolean
        boolean result = true;

        // Deklarasikan variabel option bertipe char dan inisialisasi nilai 'C'
        char option;
        option = 'C'; // memberi nilai 'C' pada variabel option

        // Deklarasikan variabel grade bertipe double dan inisialisasi 0.0
        double grade = 0.0;

        // Tugas II-1 No. 3: Cetak isi dari variabel-variabel tersebut di console
        System.out.println("The value of result=" + result);
        System.out.println("The value of option=" + option);
        System.out.println("The value of grade=" + grade);
    }
}
